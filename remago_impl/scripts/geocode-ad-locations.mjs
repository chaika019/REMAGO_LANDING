const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const inMinskArea = (lat, lng) => lat > 53.7 && lat < 54.1 && lng > 27.2 && lng < 27.9

async function geocode(queries) {
  for (const q of queries) {
    const params = new URLSearchParams({
      q, format: 'jsonv2', limit: '1', countrycodes: 'by', 'accept-language': 'ru',
      viewbox: '27.35,54.00,27.80,53.80',
    })
    const res = await fetch(`https://nominatim.openstreetmap.org/search?${params}`, {
      headers: { 'User-Agent': 'remago-site-geocoder/1.0 (local script)' },
    })
    await wait(1100)
    if (!res.ok) continue
    const data = await res.json()
    if (data[0]) {
      const lat = Number(Number(data[0].lat).toFixed(6))
      const lng = Number(Number(data[0].lon).toFixed(6))
      if (inMinskArea(lat, lng)) return [lat, lng]
    }
  }
  return null
}

